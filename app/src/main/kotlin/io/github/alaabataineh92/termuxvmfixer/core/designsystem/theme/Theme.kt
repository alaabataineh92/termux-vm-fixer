data class StatusPalette(
    val success: StatusTone,
    val warning: StatusTone,
    val neutral: StatusTone,
)

private val LightStatusPalette = StatusPalette(
    success = StatusColors.SuccessLight,
    warning = StatusColors.WarningLight,
    neutral = StatusColors.NeutralLight,
)

private val DarkStatusPalette = StatusPalette(
    success = StatusColors.SuccessDark,
    warning = StatusColors.WarningDark,
    neutral = StatusColors.NeutralDark,
)

val LocalStatusPalette = staticCompositionLocalOf { LightStatusPalette }

@Composable
fun TermuxVmFixerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current

    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkScheme
        else -> LightScheme
    }

    CompositionLocalProvider(
        LocalStatusPalette provides if (darkTheme) DarkStatusPalette else LightStatusPalette,
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            shapes = AppShapes,
            typography = AppTypography,
            content = content,
        )
    }
}
